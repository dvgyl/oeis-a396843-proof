def is_power_two(n: int) -> bool:
    return n > 0 and n & (n - 1) == 0


def source_recursion(bound: int, second: bool = False) -> list[int]:
    """Coefficient extraction from G(x-x^2)=x[-x^2]+G(x)^2."""
    a = [0, 1]
    for n in range(2, bound + 1):
        square = sum(a[k] * a[n - k] for k in range(1, n))
        substitution = sum((-1) ** (j + 1) * math.comb(n - j, j) * a[n - j]
                           for j in range(1, n // 2 + 1))
        a.append(square + substitution - int(second and n == 2))
    return a


def catalan_power(n: int, k: int) -> int:
    """[x^n] C(x)^k for C=x+C^2, using the integer Lagrange coefficient."""
    if k == 0:
        return int(n == 0)
    if n < k:
        return 0
    numerator = k * math.comb(2 * n - k, n - k)
    assert numerator % (2 * n - k) == 0
    return numerator // (2 * n - k)


def nested_square(bound: int, second: bool = False) -> list[int]:
    """Positive recursion from G=T+(G o C)^2, independently of source signs."""
    g = [0]
    composed = [0]
    for n in range(1, bound + 1):
        forcing = int(n == 1) if second else catalan_power(n, 1)
        g.append(forcing + sum(composed[k] * composed[n - k] for k in range(1, n)))
        composed.append(sum(g[k] * catalan_power(n, k) for k in range(1, n + 1)))
    return g


def nested_binomial(bound: int) -> list[int]:
    """A392210 source recurrence through its shifted binomial transform."""
    g, composed = [0], [0]
    for n in range(1, bound + 1):
        g.append(int(n == 1) + sum(composed[k] * composed[n - k] for k in range(1, n)))
        composed.append(sum(math.comb(n - 1, k - 1) * g[k] for k in range(1, n + 1)))
    return g


def multiply(a: list[int], b: list[int], bound: int) -> list[int]:
    out = [0] * (bound + 1)
    for i, ai in enumerate(a[:bound + 1]):
        for j, bj in enumerate(b[:bound + 1 - i]):
            out[i + j] += ai * bj
    return out


def compose(outer: list[int], inner: list[int], bound: int) -> list[int]:
    """Literal polynomial multiplication, independent of binomial formulas."""
    assert inner[0] == 0
    out = [0] * (bound + 1)
    power = [1] + [0] * bound
    for value in outer[:bound + 1]:
        for n, c in enumerate(power):
            out[n] += value * c
        power = multiply(power, inner, bound)
    return out


