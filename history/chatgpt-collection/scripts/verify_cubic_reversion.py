def pad(a: list[int], degree: int) -> list[int]:
    return (a + [0] * (degree + 1))[: degree + 1]


def add(a: list[int], b: list[int], degree: int) -> list[int]:
    return [x + y for x, y in zip(pad(a, degree), pad(b, degree))]


def scale(a: list[int], c: int, degree: int) -> list[int]:
    return [c * x for x in pad(a, degree)]


def mul(a: list[int], b: list[int], degree: int) -> list[int]:
    result = [0] * (degree + 1)
    for i, ai in enumerate(a[: degree + 1]):
        if ai:
            for j, bj in enumerate(b[: degree + 1 - i]):
                result[i + j] += ai * bj
    return result


def power(a: list[int], exponent: int, degree: int) -> list[int]:
    result = pad([1], degree)
    base = pad(a, degree)
    while exponent:
        if exponent & 1:
            result = mul(result, base, degree)
        base = mul(base, base, degree)
        exponent //= 2
    return result


def compose(a: list[int], b: list[int], degree: int) -> list[int]:
    assert b[0] == 0
    result = [0] * (degree + 1)
    for ai in reversed(a[: degree + 1]):
        result = mul(result, b, degree)
        result[0] += ai
    return result


def monomial(degree: int, exponent: int, coefficient: int = 1) -> list[int]:
    result = [0] * (degree + 1)
    if exponent <= degree:
        result[exponent] = coefficient
    return result


def substitution_x_power(a: list[int], exponent: int, degree: int,
                         factor: int = 1) -> list[int]:
    result = [0] * (degree + 1)
    for i, ai in enumerate(a[: degree // exponent + 1]):
        result[exponent * i] = ai * factor**i
    return result


def a389474_source_residual(a: list[int], degree: int) -> list[int]:
    """A(x²+2x³+2A²)-3A², directly from the original OEIS equation."""
    square = mul(a, a, degree)
    argument = add(add(monomial(degree, 2), monomial(degree, 3, 2), degree),
                   scale(square, 2, degree), degree)
    return add(compose(a, argument, degree), scale(square, -3, degree), degree)


def cubic_source_residual(a: list[int], sign: int, degree: int) -> list[int]:
    """A(3x²)-2x²-A²-2sA³; s=-1 is the A389475 source equation."""
    square = mul(a, a, degree)
    cube = mul(square, a, degree)
    return add(add(add(substitution_x_power(a, 2, degree, 3),
                       monomial(degree, 2, -2), degree),
                   scale(square, -1, degree), degree),
               scale(cube, -2 * sign, degree), degree)


def solve_from_source(degree: int, *, oeis: str | None = None,
                      sign: int | None = None) -> list[int]:
    """Solve successive source-equation coefficients with exact division by two."""
    assert (oeis == "A389474") != (sign is not None)
    a = [0, 1]
    for n in range(2, degree + 1):
        a.append(0)
        residual = (a389474_source_residual(a, n + 1) if oeis == "A389474"
                    else cubic_source_residual(a, sign, n + 1))
        numerator = residual[n + 1]
        assert numerator % 2 == 0, (oeis, sign, n, numerator)
        a[n] = numerator // 2
    return a


def inverse_from_composition(a: list[int], degree: int) -> list[int]:
    """Revert a normalized series by solving A(B(x))=x coefficient by coefficient."""
    assert a[:2] == [0, 1]
    b = [0, 1]
    for n in range(2, degree + 1):
        b.append(0)
        b[n] = -compose(a, b, n)[n]
    return b


def run(degree: int) -> dict:
    if degree < 24:
        raise ValueError("degree must be at least 24 to check every recorded source term")
    a = solve_from_source(degree, oeis="A389474")
    b = solve_from_source(degree, sign=-1)
    r = solve_from_source(degree, sign=1)
    series = {"A389474": a, "A389475": b}
    source_checks = {}
    for name, expected in PREFIXES.items():
        assert series[name][1:len(expected) + 1] == expected, name
        source_checks[name] = {
            "url": f"https://oeis.org/{name}",
            "source_checked_on": "2026-10-24",
            "author": "Paul D. Hanna",
            "offset": 1,
            "prefix_terms_checked": len(expected),
            "prefix_matched": True,
            "computed_coefficients_1_through_degree": series[name][1:],
        }
    assert a389474_source_residual(a, degree + 1) == [0] * (degree + 2)
    assert cubic_source_residual(b, -1, degree + 1) == [0] * (degree + 2)
    assert cubic_source_residual(r, 1, degree + 1) == [0] * (degree + 2)
    assert inverse_from_composition(a, degree) == r
    assert inverse_from_composition(r, degree) == a
    assert compose(a, r, degree) == monomial(degree, 1)
    assert compose(r, a, degree) == monomial(degree, 1)

    square_a = mul(a, a, degree)
    target_a = add(monomial(degree, 2), monomial(degree, 3, 2), degree)
    assert all((u - v) % 9 == 0 for u, v in zip(square_a, target_a))
    a_x3 = substitution_x_power(a, 3, degree)
    # k above floor(degree/3) gives zero on both sides in this truncation.
    max_k = degree // 3 + 1
    for k in range(max_k + 1):
        left = power(a, 3 * k, degree)
        right = power(a_x3, k, degree)
        assert all((u - v) % 3 == 0 for u, v in zip(left, right)), k
    cube_b = power(b, 3, degree)
    b_x3 = substitution_x_power(b, 3, degree)
    assert all((u - v) % 3 == 0 for u, v in zip(cube_b, b_x3))
    square_b = mul(b, b, degree)
    target_b = add(monomial(degree, 2), scale(b_x3, 2, degree), degree)
    assert all((u - v) % 3 == 0 for u, v in zip(square_b, target_b))
