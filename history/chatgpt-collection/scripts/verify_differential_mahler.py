#!/usr/bin/env python3
"""Independent finite checks for the A397588 and A389536 source sequences.

AI-generated by OpenAI ChatGPT for Dev Goyal. The universal proofs are in
lean/Round3/{DifferentialParity,MahlerParity}.lean; this program supplies
separate exact-integer corroboration and a source-prefix check.
"""

from __future__ import annotations

import argparse
import json
import math
import platform
from pathlib import Path


DIFFERENTIAL_PREFIX = [
    1, 3, 24, 285, 4284, 75978, 1530720, 34237485, 837481140,
    22170740526, 630399084912, 19141524214722, 617861322312696,
    21122842522288500, 762448141026794880, 28980030721635717885,
    1157145229347334181604, 48434042350706316375942,
    2121007271655295076291280, 97002622108401462159296310,
]

MAHLER_PREFIX = [
    1, 2, 2, 8, 10, 12, 32, 80, 202, 356, 540, 944, 1552, 2688,
    5648, 12544, 27850, 60980, 133380, 290320, 615212, 1250024,
    2422336, 4537056, 8352016, 15256736, 28031232, 52183296,
    97737488, 182819808, 341588800, 641495936, 1221153226,
    2372077780,
]


def multiply(a: list[int], b: list[int], bound: int) -> list[int]:
    out = [0] * (bound + 1)
    for i, av in enumerate(a[: bound + 1]):
        if av:
            for j, bv in enumerate(b[: bound + 1 - i]):
                out[i + j] += av * bv
    return out


def compose(outer: list[int], inner: list[int], bound: int) -> list[int]:
    assert inner[0] == 0
    out = [0] * (bound + 1)
    power = [1] + [0] * bound
    for value in outer[: bound + 1]:
        for degree, coefficient in enumerate(power):
            out[degree] += value * coefficient
        power = multiply(power, inner, bound)
    return out


def is_power_of_two(n: int) -> bool:
    return n > 0 and n & (n - 1) == 0


def differential_coefficients(bound: int) -> list[int]:
    """The source recurrence, without using any congruence theorem."""
    a = [0, 1]
    for n in range(2, bound + 1):
        a.append((n + 1) * sum(a[k] * a[n - k] for k in range(1, n)))
    return a


def mahler_coefficients(bound: int) -> list[int]:
    """Extract [x^(n+1)] A(x^2(1+2x)) = [x^n] A(x)."""
    a = [0, 1]
    for n in range(2, bound + 1):
        a.append(sum(a[j] * math.comb(j, n + 1 - 2 * j)
                     * 2 ** (n + 1 - 2 * j)
                     for j in range((n + 3) // 3, (n + 1) // 2 + 1)))
    return a


def run(differential_bound: int = 500, mahler_bound: int = 2050,
        composition_bound: int = 80) -> dict:
    assert differential_bound >= len(DIFFERENTIAL_PREFIX)
    assert mahler_bound >= max(len(MAHLER_PREFIX), composition_bound)
    d = differential_coefficients(differential_bound)
    m = mahler_coefficients(mahler_bound)
    assert d[1: len(DIFFERENTIAL_PREFIX) + 1] == DIFFERENTIAL_PREFIX
    assert m[1: len(MAHLER_PREFIX) + 1] == MAHLER_PREFIX

    # Literal differential equation, evaluated with exact polynomial arithmetic.
    square = multiply(d, d, differential_bound)
    for n in range(differential_bound + 1):
        assert d[n] == int(n == 1) + (n + 1) * square[n], n
        assert (d[n] % 2 == 1) == is_power_of_two(n), n
        if n > 1:
            assert d[n] % 3 == 0, n

    # Literal substitution, independently evaluated by polynomial multiplication.
    composed = compose(m, [0, 0, 1, 2], composition_bound + 1)
    assert composed == [0] + m[: composition_bound + 1]

    # Check both source cases and the stronger Catalan-series comparison.
    catalan = 1
    for n in range(2, mahler_bound + 1):
        expected = 2 if is_power_of_two(n - 1) else 0
        assert m[n] % 4 == expected, n
        assert (m[n] - 2 * catalan) % 4 == 0, n
        k = n - 2
        numerator = catalan * 2 * (2 * k + 1)
        assert numerator % (k + 2) == 0
        catalan = numerator // (k + 2)

    return {
        "status": "PASS",
        "python": platform.python_version(),
        "purpose": "Finite corroboration only; the all-index proofs are verified in Lean.",
        "source_access_date": "2026-10-24",
        "A397588": {
            "source": "https://oeis.org/A397588",
            "offset": 1,
            "source_prefix_terms_matched": len(DIFFERENTIAL_PREFIX),
            "literal_differential_equation_indices": [0, differential_bound],
            "parity_indices": [0, differential_bound],
            "divisibility_by_three_indices": [2, differential_bound],
            "odd_indices": [n for n in range(differential_bound + 1)
                            if d[n] % 2],
        },
        "A389536": {
            "source": "https://oeis.org/A389536",
            "offset": 1,
            "source_prefix_terms_matched": len(MAHLER_PREFIX),
            "literal_composition_equation_coefficients": [0, composition_bound + 1],
            "complete_residue_pattern_indices": [2, mahler_bound],
            "catalan_comparison_indices": [2, mahler_bound],
            "residue_two_indices": [n for n in range(2, mahler_bound + 1)
                                    if m[n] % 4 == 2],
        },
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    payload = json.dumps(run(), indent=2) + "\n"
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(payload)
    print(payload, end="")


if __name__ == "__main__":
    main()
