#!/usr/bin/env python3
"""Finite independent checks for OEIS A380056.

AI-generated by OpenAI ChatGPT for Dev Goyal. The all-index proofs are in
lean/Round4/ExpCosine.lean. This program checks exact integer coefficients
against a separate rational power-series division and the official prefix.
"""

from __future__ import annotations

import argparse
import json
import math
import platform
from fractions import Fraction
from pathlib import Path


SOURCE_PREFIX = [
    1, 1, 13, 25, 441, 1261, 30213, 115025, 3529201, 16792021,
    629401213, 3593565625, 159175688361, 1060279600381,
    54189700721013, 412526870321825, 23894940183997921,
    204641610743378341, 13248060325188261613,
    126065945039257743625, 9020317522757414377881,
    94419130586604915837901,
]


def cosine_derivative(n: int) -> int:
    return 0 if n % 2 else (-4) ** (n // 2)


def integer_coefficients(degree: int) -> list[int]:
    out = [0]
    for n in range(1, degree + 1):
        out.append(1 - sum(math.comb(n, k) * out[k] *
                           cosine_derivative(n-k) for k in range(n)))
    return out


def rational_quotient(degree: int) -> tuple[list[Fraction], list[Fraction]]:
    """Ordinary coefficient division of (exp(x)-1) by literal cos(2x)."""
    numerator = [Fraction(0)] + [Fraction(1, math.factorial(n))
                                  for n in range(1, degree+1)]
    denominator = [Fraction((-1) ** (n//2) * 2**n, math.factorial(n))
                   if n % 2 == 0 else Fraction(0)
                   for n in range(degree+1)]
    quotient: list[Fraction] = []
    for n in range(degree+1):
        quotient.append((numerator[n] - sum(
            denominator[j] * quotient[n-j] for j in range(1, n+1))) /
            denominator[0])
    for n in range(degree+1):
        assert sum(denominator[j]*quotient[n-j]
                   for j in range(n+1)) == numerator[n], n
    return quotient, denominator


def run(degree: int = 400, rational_degree: int = 80) -> dict:
    assert degree >= max(len(SOURCE_PREFIX), rational_degree)
    assert rational_degree >= len(SOURCE_PREFIX)
    a = integer_coefficients(degree)
    q, _ = rational_quotient(rational_degree)
    assert a[1:len(SOURCE_PREFIX)+1] == SOURCE_PREFIX
    for n in range(rational_degree+1):
        assert q[n]*math.factorial(n) == a[n], n
    for n in range(degree+1):
        assert sum(math.comb(n, k)*a[k]*cosine_derivative(n-k)
                   for k in range(n+1)) == int(n > 0), n
        assert a[n] % 5 == (2*pow(2, n, 5)+3*pow(4, n, 5)) % 5, n
        assert a[n] % 5 == [0, 1, 1, 3][n % 4], n
        assert (a[n] % 5 == 0) == (n % 4 == 0), n
        if n > 0:
            assert a[n] % 4 == 1, n
        if n+4 <= degree:
            assert a[n+4] % 5 == a[n] % 5, n
    return {
        "status": "PASS",
        "python": platform.python_version(),
        "purpose": "Finite corroboration only; all-index results are separate Lean theorems.",
        "source_access_date": "2026-10-24",
        "A380056": {
            "source": "https://oeis.org/A380056",
            "offset": 1,
            "source_prefix_terms_matched": len(SOURCE_PREFIX),
            "integer_binomial_convolution_indices": [0, degree],
            "independent_rational_quotient_and_literal_equation_degrees": [0, rational_degree],
            "modulo_four_indices": [1, degree],
            "modulo_five_formula_and_exact_divisibility_indices": [0, degree],
            "modulo_five_period": 4,
            "modulo_five_residues_by_index_mod_four": [0, 1, 1, 3],
            "first_twelve_terms": a[1:13],
        },
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--degree", type=int, default=400)
    parser.add_argument("--rational-degree", type=int, default=80)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    payload = json.dumps(run(args.degree, args.rational_degree), indent=2) + "\n"
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(payload)
    print(payload, end="")


if __name__ == "__main__":
    main()
