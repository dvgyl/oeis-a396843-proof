def source_residual(a: list[int], degree: int) -> list[int]:
    argument = add(a, monomial(degree, 1, -1), degree)
    return add(compose(a, argument, degree), scale(mul(a,a,degree),-1,degree), degree)


def source_solution(degree: int) -> list[int]:
    a = [0,1]
    for n in range(2,degree+1):
        a.append(0)
        a[n] = -source_residual(a,n)[n]
    return a


def binary_power(n: int) -> bool:
    return n>0 and n & (n-1)==0


