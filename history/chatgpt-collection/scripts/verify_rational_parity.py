from __future__ import annotations

import argparse
import json
import math
import platform
from pathlib import Path


SOURCE_PREFIX = [
    0, 1, 6, 33, 174, 892, 4480, 22149, 108144, 522685,
    2505112, 11921919, 56396508, 265403751, 1243376476, 5802001140,
    26979276974, 125062092939, 578101278342, 2665535043771,
    12262237690928, 56292277012925, 257928385148946, 1179746378224461,
    5387375927372810, 24565077404044268, 111855801487635036,
]


def multiply(a: list[int], b: list[int], bound: int | None = None) -> list[int]:
    length = len(a) + len(b) - 1
    if bound is not None:
        length = min(length, bound + 1)
    out = [0] * length
    for i, av in enumerate(a):
        if av == 0:
            continue
        for j, bv in enumerate(b[: max(0, length - i)]):
            out[i + j] += av * bv
    return out


def compose(outer: list[int], inner: list[int], bound: int) -> list[int]:
    assert inner[0] == 0
    out = [0] * (bound + 1)
    power = [1]
    for coefficient in outer[: bound + 1]:
        for degree, value in enumerate(power):
            out[degree] += coefficient * value
        power = multiply(power, inner, bound)
    return out


def rational_coefficients(bound: int) -> tuple[list[int], list[int], list[int]]:
    u = [1, -1]
    v = [1, -3, 1]
    w = [1, -7, 13, -7, 1]
    numerator = [0] + multiply(multiply(u, u), multiply(v, v))
    denominator = multiply(w, w)
    assert denominator[0] == 1
    coefficients = []
    for n in range(bound + 1):
        rhs = numerator[n] if n < len(numerator) else 0
        rhs -= sum(denominator[j] * coefficients[n - j]
                   for j in range(1, min(n + 1, len(denominator))))
        coefficients.append(rhs)
    return coefficients, numerator, denominator


def binomial_formula(n: int) -> int:
    return sum(j * math.comb(n + i - 1, 2 * i - 1)
               * math.comb(i + j - 1, 2 * j - 1)
               for i in range(1, n + 1) for j in range(1, i + 1))


def run(bound: int = 2000, composition_bound: int = 80) -> dict:
    assert bound >= max(composition_bound, 30)
    coefficients, numerator, denominator = rational_coefficients(bound)
    assert coefficients[: len(SOURCE_PREFIX)] == SOURCE_PREFIX

    # The original source definition is composed directly, without using a parity formula.
    b = list(range(composition_bound + 1))
    b2 = compose(b, b, composition_bound)
    b3 = compose(b, b2, composition_bound)
    assert b3 == coefficients[: composition_bound + 1]

    for n in range(31):
        assert coefficients[n] == binomial_formula(n), n

    # Exact finite polynomial identity over F_2, independent of coefficient sampling.
    period_numerator = [0, 1, 0, 1, 0, 0, 0, 1, 0, 1]
    period_denominator = [1] + [0] * 9 + [1]
    lhs = multiply(numerator, period_denominator)
    rhs = multiply(denominator, period_numerator)
    polynomial_checks = max(len(lhs), len(rhs))
    lhs += [0] * (polynomial_checks - len(lhs))
    rhs += [0] * (polynomial_checks - len(rhs))
    assert all((u - v) % 2 == 0 for u, v in zip(lhs, rhs))

    for n, value in enumerate(coefficients):
        assert value % 2 == (n % 10 in {1, 3, 7, 9}), n
    for n in range(1, bound // 2 + 1):
        assert coefficients[2 * n] % 2 == 0, n
        assert (coefficients[2 * n - 1] % 2 == 0) == (n % 5 == 3), n

    return {
        "status": "PASS",
        "python": platform.python_version(),
        "purpose": "Independent finite source-definition and parity corroboration; universal proof is in Lean.",
        "source": "https://oeis.org/A396093",
        "source_access_date": "2026-10-24",
        "offset": 0,
        "source_prefix_terms_matched": len(SOURCE_PREFIX),
        "direct_third_composition_indices": [0, composition_bound],
        "independent_double_binomial_indices": [0, 30],
        "polynomial_identity_coefficients_checked": polynomial_checks,
        "complete_parity_pattern_indices": [0, bound],
        "conjecture_1_parameter_indices": [1, bound // 2],
        "conjecture_2_parameter_indices": [1, bound // 2],
        "odd_residues_mod_10": [1, 3, 7, 9],
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    payload = json.dumps(run(), indent=2) + "\n"
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(payload)
    print(payload, end="")


if __name__ == "__main__":
    main()
