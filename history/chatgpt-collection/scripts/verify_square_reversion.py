#!/usr/bin/env python3
"""Independent exact-integer checks for OEIS A389542.

AI-generated by OpenAI ChatGPT for Dev Goyal. Finite checks corroborate the
source identification; the universal proof is in Round3.SquareReversion.
The source recurrence and the auxiliary-series construction are compared.
Only Python standard-library arithmetic is used; there is no network access.
"""

from __future__ import annotations

import argparse
import json
import platform
from pathlib import Path

from verify_cubic_reversion import (
    add, compose, inverse_from_composition, monomial, mul, scale,
    substitution_x_power,
)


SOURCE_PREFIX = [
    1, 2, 10, 64, 446, 3328, 26004, 209856, 1735734, 14636032,
    125342732, 1087209472, 9531523756, 84323339264, 751827499816,
    6748864069632, 60943035344934, 553222761873408,
    5045557910629596, 46210534990774272, 424830847120966020,
    3919044736906690560,
]


def source_residual(a: list[int], degree: int) -> list[int]:
    """A(A(x)^2-x^2)-4*A(x)^3, directly from the OEIS equation."""
    square = mul(a, a, degree)
    argument = add(square, monomial(degree, 2, -1), degree)
    return add(compose(a, argument, degree),
               scale(mul(square, a, degree), -4, degree), degree)


def solve_from_source(degree: int) -> list[int]:
    """Solve each source coefficient, checking the required division by two."""
    a = [0, 1]
    for n in range(2, degree + 1):
        a.append(0)
        residual = source_residual(a, n + 1)
        numerator = -residual[n + 1]
        assert numerator % 2 == 0, (n, numerator)
        a[n] = numerator // 2
    return a


def auxiliary_l(degree: int) -> list[int]:
    """L=x+L^2-2*x*L(4*x^3), with coefficient-one triangular recursion."""
    l = [0, 1] + [0] * (degree - 1)
    for n in range(2, degree + 1):
        l[n] = sum(l[i] * l[n - i] for i in range(1, n))
        if (n - 1) % 3 == 0:
            j = (n - 1) // 3
            l[n] -= 2 * 4**j * l[j]
    return l


def power_of_two(n: int) -> bool:
    return n > 0 and n & (n - 1) == 0


def run(degree: int) -> dict:
    if degree < len(SOURCE_PREFIX):
        raise ValueError("degree must check all 22 recorded source terms")
    a = solve_from_source(degree)
    l = auxiliary_l(degree)
    r = [0, 1] + [-2 * l[n - 1] for n in range(2, degree + 1)]
    assert a[1:len(SOURCE_PREFIX) + 1] == SOURCE_PREFIX
    assert inverse_from_composition(r, degree) == a
    assert inverse_from_composition(a, degree) == r
    assert source_residual(a, degree + 1) == [0] * (degree + 2)
    assert compose(a, r, degree) == monomial(degree, 1)
    assert compose(r, a, degree) == monomial(degree, 1)

    l_square = mul(l, l, degree)
    l_sub = substitution_x_power(l, 3, degree, 4)
    l_target = add(add(monomial(degree, 1), l_square, degree),
                   scale(mul(monomial(degree, 1), l_sub, degree), -2, degree),
                   degree)
    assert l == l_target
    inverse_residual = add(add(mul(r, r, degree + 1),
                               substitution_x_power(r, 3, degree + 1, 4),
                               degree + 1),
                           monomial(degree + 1, 2, -1), degree + 1)
    assert inverse_residual == [0] * (degree + 2)
    assert all(l[n] % 2 == int(power_of_two(n))
               for n in range(degree + 1))
    assert all((a[n] - r[n]) % 4 == 0 for n in range(degree + 1))
    assert all(a[n] % 4 == (2 if power_of_two(n - 1) else 0)
               for n in range(2, degree + 1))

    return {
        "schema_version": 1,
        "ai_disclosure": "Generated by ChatGPT (OpenAI) for Dev Goyal.",
        "status": "passed",
        "arithmetic": "unbounded Python integers, exact division checked",
        "python_version": platform.python_version(),
        "degree": degree,
        "bounds_are_not_universal_proofs": True,
        "proof_modules": ["Round3.SquareReversion"],
        "source": {
            "oeis": "A389542",
            "url": "https://oeis.org/A389542",
            "source_checked_on": "2026-10-24",
            "author": "Paul D. Hanna",
            "offset": 1,
            "prefix_terms_checked": len(SOURCE_PREFIX),
            "prefix_matched": True,
            "computed_coefficients_1_through_degree": a[1:],
        },
        "checks": {
            "original_source_equation_through_degree": degree + 1,
            "inverse_equation_through_degree": degree + 1,
            "auxiliary_equation_through_degree": degree,
            "both_compositional_inverse_directions_through_degree": degree,
            "canonical_and_direct_source_recursions_agree": True,
            "L_power_of_two_parity_indices": [0, degree],
            "A_equal_R_mod_four_indices": [0, degree],
            "A389542_conjectured_residues_indices": [2, degree],
            "indices_with_residue_two": [
                n for n in range(2, degree + 1) if a[n] % 4 == 2
            ],
        },
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--degree", type=int, default=80)
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1]
                        / "validation" / "square_reversion_numeric.json")
    args = parser.parse_args()
    result = run(args.degree)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(f"PASS: A389542, both integral recursions and modulus-four theorem "
          f"through degree {args.degree}; evidence: {args.output}")


if __name__ == "__main__":
    main()
