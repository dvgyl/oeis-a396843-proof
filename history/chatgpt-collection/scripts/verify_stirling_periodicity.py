from __future__ import annotations

import argparse
import json
import math
import platform
from pathlib import Path


PREFIXES = {
    "A052895": [1, 1, 5, 43, 545, 9211, 195305, 4990483, 149371745, 5128125451],
    "A064618": [1, 1, 5, 49, 821, 21121, 775205, 38516689, 2490976661, 203419086241],
    "A354242": [1, 2, 14, 158, 2486, 50222, 1239254, 36126638, 1214933846],
    "A167137": [1, 1, 5, 31, 257, 2551, 30065, 407191, 6214577, 105530071],
    "A305550": [1, 1, 3, 19, 135, 1171, 12543, 156619, 2185095, 33787171],
    "A306082": [1, 1, 3, 13, 99, 901, 8763, 92653, 1125939, 16333141],
    "A080253": [1, 3, 17, 147, 1697, 24483, 423857, 8560947, 197613377, 5131725123],
}


def totient(n: int) -> int:
    """Independent elementary computation from coprime residues."""
    return sum(math.gcd(n, j) == 1 for j in range(1, n + 1))


def partition_weights(nmax: int, *, distinct: bool = False, squares: bool = False) -> list[int]:
    weights = [1] + [0] * nmax
    parts = range(1, nmax + 1)
    if squares:
        parts = [j * j for j in range(1, math.isqrt(nmax) + 1)]
    for part in parts:
        targets = range(nmax, part - 1, -1) if distinct else range(part, nmax + 1)
        for n in targets:
            weights[n] += weights[n - part]
    return weights


def all_weights(nmax: int) -> dict[str, list[int]]:
    factorials = [math.factorial(k) for k in range(nmax + 1)]
    pell = [1, 3]
    while len(pell) <= nmax:
        pell.append(2 * pell[-1] + pell[-2])
    return {
        "A052895": [math.comb(2 * k, k) // (k + 1) for k in range(nmax + 1)],
        "A064618": factorials,
        "A354242": [math.comb(2 * k, k) for k in range(nmax + 1)],
        "A167137": partition_weights(nmax),
        "A305550": partition_weights(nmax, distinct=True),
        "A306082": partition_weights(nmax, squares=True),
        "A080253": pell[: nmax + 1],
        "signed_test_weights": [(-1) ** k * (k * k + 3) for k in range(nmax + 1)],
    }


def transform_sequences(weights: dict[str, list[int]], nmax: int) -> dict[str, list[int]]:
    """Use ordered-surjection recurrence T(n+1,k)=k(T(n,k)+T(n,k-1))."""
    result = {name: [] for name in weights}
    row = [1]
    for n in range(nmax + 1):
        for name, coeffs in weights.items():
            result[name].append(sum(coeffs[k] * row[k] for k in range(n + 1)))
        padded = row + [0]
        row = [0] + [k * (padded[k] + padded[k - 1]) for k in range(1, n + 2)]
    return result


def independently_check_inclusion_exclusion(nmax: int = 18) -> int:
    row = [1]
    checks = 0
    for n in range(nmax + 1):
        for k in range(n + 1):
            alternate = sum((-1) ** (k - j) * math.comb(k, j) * j**n for j in range(k + 1))
            assert row[k] == alternate, (n, k, row[k], alternate)
            checks += 1
        padded = row + [0]
        row = [0] + [k * (padded[k] + padded[k - 1]) for k in range(1, n + 2)]
    return checks


def run(max_modulus: int) -> dict:
    periods = {m: totient(m) for m in range(1, max_modulus + 1)}
    nmax = max(max(len(values) for values in PREFIXES.values()),
               max(m + 3 * p for m, p in periods.items()))
    sequences = transform_sequences(all_weights(nmax), nmax)
    source_checks = {}
    for name, prefix in PREFIXES.items():
        assert sequences[name][: len(prefix)] == prefix, name
        source_checks[name] = {"offset": 0, "terms_checked": len(prefix), "matched": True,
                               "source": f"https://oeis.org/{name}"}
    identity_checks = independently_check_inclusion_exclusion()
    total_checks = 0
    details = {}
    for name, sequence in sequences.items():
        checks = 0
        for modulus, period in periods.items():
            assert period > 0
            for n in range(modulus, modulus + 2 * period + 1):
                assert (sequence[n + period] - sequence[n]) % modulus == 0, (name, modulus, n)
                checks += 1
        details[name] = checks
        total_checks += checks
    power_checks = 0
    for modulus, period in periods.items():
        for a in range(2 * modulus + 1):
            for n in [modulus, modulus + 1, modulus + period]:
                assert pow(a, n + period, modulus) == pow(a, n, modulus), (modulus, a, n)
                power_checks += 1
    return {
        "status": "PASS",
        "python": platform.python_version(),
        "purpose": "Finite corroboration only; universal verification is the Lean build.",
        "source_access_date": "2026-10-24",
        "prefix_checks": source_checks,
        "independent_inclusion_exclusion_checks": identity_checks,
        "moduli_checked": [1, max_modulus],
        "indices_checked_per_modulus": "m <= n <= m + 2*phi(m), inclusive",
        "maximum_generated_index": nmax,
        "periodicity_checks_by_sequence": details,
        "periodicity_checks_total": total_checks,
        "power_periodicity_checks": power_checks,
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--max-modulus", type=int, default=128)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    if args.max_modulus < 1:
        parser.error("--max-modulus must be positive")
    report = run(args.max_modulus)
    payload = json.dumps(report, indent=2) + "\n"
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(payload)
    print(payload, end="")


if __name__ == "__main__":
    main()
