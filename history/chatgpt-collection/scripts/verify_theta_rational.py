def multiply(a: list[int], b: list[int], degree: int) -> list[int]:
    result = [0] * (degree + 1)
    for i, av in enumerate(a[:degree + 1]):
        if av:
            for j, bv in enumerate(b[:degree + 1 - i]):
                if bv:
                    result[i + j] += av * bv
    return result


def power(a: list[int], exponent: int, degree: int) -> list[int]:
    result = [1] + [0] * degree
    while exponent:
        if exponent % 2:
            result = multiply(result, a, degree)
        exponent //= 2
        if exponent:
            a = multiply(a, a, degree)
    return result


def inverse(a: list[int], degree: int) -> list[int]:
    assert a[0] == 1
    result = [1]
    for n in range(1, degree + 1):
        result.append(-sum(a[k] * result[n - k]
                           for k in range(1, min(n + 1, len(a)))))
    return result


